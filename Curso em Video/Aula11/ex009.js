// Condições: if, else

// Exemplo de condição Simples:
var vel = 78.2
console.log(`A velocidade foi de ${vel}Km/h`)
if (vel > 60) {
    console.log('Velocidade acima do permitido. MULTADO!')
}
console.log('Dirija com segurança.')

// Exemplo de condição Composta:
var pais = 'Brasil'
if (pais == 'Brasil') {
    console.log('Você é brasileiro.')
} else {
    console.log('Você é estrangeiro.')
}


